#ifndef CDC_CMD_H
#define CDC_CMD_H

#include <stdbool.h>
#include <stdint.h>

//--------------------------------------------------------------------+
// CDC 虚拟串口指令模块（上位机 → 设备）
//   行文本协议：\r 或 \n 任一结束，大小写不敏感，统一回 "OK" / "ERR n"。
//   纯非阻塞：靠主循环调用 cdc_cmd_task()，绝不做 printf / sleep_ms，
//   以免卡住音频路径（每毫秒要送 288 字节 iso 数据）。
//--------------------------------------------------------------------+

// 单行最大长度（含结束符前的全部字符），超出即丢弃并回 ERR 2
#define CDC_CMD_LINE_MAX 64

// 半行超时：收到首字符后这么久没等到结束符就丢弃（防上位机发残缺行卡死缓冲）
#define CDC_CMD_LINE_TIMEOUT_MS 200

// 主机看门狗：接管状态下这么久没收到任何指令，就自动交还本地控制
// （上位机崩溃 / 拔线后，灯不会永远卡在最后一个状态）
#define CDC_HOST_TIMEOUT_MS 5000

//--------------------------------------------------------------------+
// 错误码表（"ERR n"）——上位机按码处理，不要猜字符串
//--------------------------------------------------------------------+
//   1 = 未知指令
//   2 = 行超长 / 半行超时（残缺行已丢弃）
//   3 = 灯名不认识（LED <name> ...）
//   4 = 参数值非法（枚举值不认识，如 SET STATE FOO）
//   5 = 缺参数 / 数字解析失败
//   6 = 配置非法（Phase A2：JSON 解析失败或字段越界，配置未被采用）
//--------------------------------------------------------------------+

void cdc_cmd_init(void);   // 复位行缓冲
void cdc_cmd_task(void);   // 主循环调用：收字节 → 成行 → 分发 → 回显

#endif // CDC_CMD_H
